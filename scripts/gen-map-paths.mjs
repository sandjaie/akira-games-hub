// Bakes src/content/maps/mapPaths.ts from Natural Earth data (world-atlas).
// Run after changing a board: node scripts/gen-map-paths.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { geoNaturalEarth1, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const BOARDS = {
  'asia-pacific': {
    bbox: [58, -46, 156, 56],
    regions: {
      india: 'India',
      china: 'China',
      japan: 'Japan',
      australia: 'Australia',
    },
  },
  europe: {
    bbox: [-12, 34, 32, 63],
    regions: {
      'united-kingdom': 'United Kingdom',
      france: 'France',
      spain: 'Spain',
      italy: 'Italy',
    },
  },
  africa: {
    bbox: [-20, -37, 54, 38],
    regions: {
      egypt: 'Egypt',
      nigeria: 'Nigeria',
      kenya: 'Kenya',
      'south-africa': 'South Africa',
    },
  },
  americas: {
    bbox: [-140, -35, -33, 72],
    regions: {
      canada: 'Canada',
      'united-states': 'United States of America',
      mexico: 'Mexico',
      brazil: 'Brazil',
    },
  },
}

const topo = JSON.parse(
  readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8'),
)
const world = feature(topo, topo.objects.countries)

const round = (d) =>
  d.replace(/-?\d+\.\d+/g, (m) => String(Math.round(Number(m))))

const intersects = (a, b) =>
  Number.isFinite(a[0][0]) &&
  a[0][0] < b[1][0] &&
  a[1][0] > b[0][0] &&
  a[0][1] < b[1][1] &&
  a[1][1] > b[0][1]

const boards = {}
for (const [boardId, def] of Object.entries(BOARDS)) {
  const [w, s, e, n] = def.bbox
  // MultiPoint, not Polygon: d3 reads polygon rings on the sphere and a
  // wrongly wound "rectangle" fits the whole globe instead of the box.
  const mx = (w + e) / 2
  const my = (s + n) / 2
  const box = {
    type: 'MultiPoint',
    coordinates: [
      [w, s],
      [mx, s],
      [e, s],
      [e, my],
      [e, n],
      [mx, n],
      [w, n],
      [w, my],
    ],
  }
  const projection = geoNaturalEarth1().fitExtent(
    [
      [0, 0],
      [1000, 1000],
    ],
    box,
  )
  const unclipped = geoPath(projection)
  const bounds = unclipped.bounds(box)
  const clipped = geoPath(geoNaturalEarth1().fitExtent([[0, 0], [1000, 1000]], box).clipExtent(bounds))

  const names = Object.values(def.regions)
  const land = []
  const regions = {}
  const labels = {}
  for (const f of world.features) {
    if (!intersects(unclipped.bounds(f), bounds)) continue
    const d = clipped(f)
    if (!d) continue
    const key = Object.keys(def.regions).find(
      (k) => def.regions[k] === f.properties.name,
    )
    if (key) {
      regions[key] = round(d)
      labels[key] = clipped.centroid(f).map((v) => Math.round(v))
    } else land.push(round(d))
  }
  const missing = names.filter(
    (name) => !Object.values(def.regions).some((v) => v === name && regions),
  )
  for (const key of Object.keys(def.regions)) {
    if (!regions[key]) throw new Error(`${boardId}: no shape for ${key}`)
  }
  if (missing.length) throw new Error(`${boardId}: missing ${missing}`)

  const [[x0, y0], [x1, y1]] = bounds
  boards[boardId] = {
    viewBox: [x0, y0, x1 - x0, y1 - y0].map((v) => v.toFixed(1)).join(' '),
    land,
    regions,
    labels,
  }
}

const body = `// GENERATED by scripts/gen-map-paths.mjs — do not edit by hand.
import type { MapBoardId, MapRegionId } from '../countries'

export type BoardPaths = {
  viewBox: string
  /** Neighbouring countries, drawn flat for context. */
  land: string[]
  regions: Record<MapRegionId, string>
  /** Where to drop a name label on reveal. */
  labels: Record<MapRegionId, [number, number]>
}

export const BOARD_PATHS: Record<MapBoardId, BoardPaths> = ${JSON.stringify(
  boards,
  null,
  2,
)} as unknown as Record<MapBoardId, BoardPaths>
`

writeFileSync('src/content/maps/mapPaths.ts', body)
console.log(
  Object.entries(boards)
    .map(([k, v]) => `${k}: ${v.land.length} land + ${Object.keys(v.regions).length} regions`)
    .join('\n'),
)
