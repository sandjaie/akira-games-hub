/**
 * Generates src/content/worldCountries.ts — the wide flag pool.
 *
 * Source is mledoze/countries, the dataset REST Countries is itself built on.
 * We take it straight from the source and commit the result: country names and
 * ISO codes change about once a decade, so fetching them at runtime buys
 * nothing and costs an outage every time an API deprecates a version (which is
 * exactly what happened to REST Countries v3.1).
 *
 * Flag images come from flagcdn.com by ISO code — keyless, CORS-open, SVG.
 *
 *   node scripts/gen-countries.mjs
 */
import { writeFileSync } from 'node:fs'

const SOURCE =
  'https://raw.githubusercontent.com/mledoze/countries/master/dist/countries.json'
const OUT = new URL('../src/content/worldCountries.ts', import.meta.url)

/**
 * Countries a child has a fair chance of knowing — the Easy pool. Everything
 * else is Medium. Picked by hand: recognisability is not population (a kid
 * knows Switzerland, not Bangladesh), so no formula gets this right.
 */
const EASY = new Set([
  'ar', 'at', 'au', 'be', 'br', 'ca', 'ch', 'cn', 'co', 'cu', 'de', 'dk', 'eg',
  'es', 'et', 'fi', 'fr', 'gb', 'gr', 'id', 'ie', 'il', 'in', 'iq', 'ir', 'is',
  'it', 'jm', 'jp', 'ke', 'kr', 'lk', 'ma', 'mx', 'my', 'ng', 'nl', 'no', 'np',
  'nz', 'pe', 'ph', 'pk', 'pl', 'pt', 'ru', 'sa', 'se', 'sg', 'th', 'tr', 'ua',
  'us', 'vn', 'za',
])

/** mledoze splits the world five ways; the game shows the Americas as two. */
function continentOf(country) {
  const { region, subregion = '' } = country
  if (region === 'Americas') {
    return subregion === 'South America' ? 'South America' : 'North America'
  }
  return region
}

const res = await fetch(SOURCE)
if (!res.ok) throw new Error(`source fetch failed: ${res.status}`)
const raw = await res.json()

const rows = raw
  // UN members only: keeps out territories and disputed entries, which are
  // unfair as quiz answers and often have no settled flag
  .filter((c) => c.independent && c.unMember)
  .map((c) => ({
    code: c.cca2.toLowerCase(),
    name: c.name.common,
    continent: continentOf(c),
    // "Asia · Central Asia" reads better than "Asia" alone on the reveal card
    subregion: c.subregion ?? '',
    capital: c.capital?.[0] ?? '',
    tier: EASY.has(c.cca2.toLowerCase()) ? 1 : 2,
  }))
  .filter((c) => c.capital && c.continent)
  .sort((a, b) => a.name.localeCompare(b.name))

const missing = [...EASY].filter((code) => !rows.some((r) => r.code === code))
if (missing.length > 0) {
  throw new Error(`Easy codes not found in source: ${missing.join(', ')}`)
}

const body = rows
  .map(
    (r) =>
      `  { code: '${r.code}', name: ${JSON.stringify(r.name)}, continent: '${
        r.continent
      }', subregion: ${JSON.stringify(r.subregion)}, capital: ${JSON.stringify(
        r.capital,
      )}, tier: ${r.tier} },`,
  )
  .join('\n')

writeFileSync(
  OUT,
  `// Generated by scripts/gen-countries.mjs — do not edit by hand.
// Source: mledoze/countries (UN member states). Flags: flagcdn.com/<code>.svg
import type { Continent } from './countries'

export type WorldCountry = {
  code: string
  name: string
  continent: Continent
  /** e.g. "Central Asia" — narrower than the continent, shown next to it. */
  subregion: string
  capital: string
  /** 1 = a child is likely to know it (Easy), 2 = wider world (Medium). */
  tier: 1 | 2
}

export const WORLD_COUNTRIES: WorldCountry[] = [
${body}
]
`,
)

const easyCount = rows.filter((r) => r.tier === 1).length
console.log(`wrote ${rows.length} countries (${easyCount} easy) to ${OUT.pathname}`)
